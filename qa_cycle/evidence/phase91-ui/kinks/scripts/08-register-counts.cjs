// 662A step 8: compute the FD-3 pack counts from the register table itself and write them between the
// <!-- counts:start --> / <!-- counts:end --> markers in kinks-register.md (re-run after every edit).
// Also validates every row: 14 cells, ids K-01…K-nn consecutive, fixed category list, "Needs decision"
// vocabulary, "Founder disposition" prefix, and that every linked screenshot / file exists.
// Usage (worktree root): node qa_cycle/evidence/phase91-ui/kinks/scripts/08-register-counts.cjs [--check]
//   --check: validate and print, do not rewrite the file.
const path = require("path");
const fs = require("fs");

const EVROOT = path.resolve(__dirname, "../..");
const REG = path.join(EVROOT, "kinks-register.md");
const SEED_MAX = 21; // K-01…K-21 (architecture §18.3.2)
const INTAKE_MAX = 46; // K-22…K-46 (661B found.md + walk/findings.md); K-47… = walk rows (T1→T5)
const CATS = ["density", "empty-state sizing", "overflow and truncation", "dark-mode break", "inconsistent primitive", "sticky and scroll", "focus and keyboard", "other"];
const SLICE_ORDER = ["661B", "663A", "663B", "663C", "664A", "664B", "665A", "665B", "665C", "665D", "665E", "665F", "666A", "666B", "667A", "667B", "668A", "669A", "669B", "670A"];
const CHECK = process.argv.includes("--check");

const text = fs.readFileSync(REG, "utf8");
const errors = [];
const rows = [];
for (const line of text.split("\n")) {
  if (!/^\| K-\d+ \|/.test(line)) continue;
  const cells = line.replace(/\\\|/g, "\u0000").split("|").slice(1, -1).map((c) => c.replace(/\u0000/g, "|").trim());
  if (cells.length !== 14) errors.push(`${cells[0]}: ${cells.length} cells (want 14)`);
  const [id, page, route, persona, vp, theme, shot, cat, symptom, fix, owner, decision, disp, closed] = cells;
  rows.push({ id, n: Number(id.slice(2)), page, route, persona, vp, theme, shot, cat, symptom, fix, owner, decision, disp, closed });
}
rows.forEach((r, i) => {
  if (r.n !== i + 1) errors.push(`${r.id}: out of sequence (expected K-${String(i + 1).padStart(2, "0")})`);
  const baseCat = r.cat.replace(/ \(contrast\)$/, "");
  if (!CATS.includes(baseCat)) errors.push(`${r.id}: category "${r.cat}"`);
  const d = r.decision.split(/[\s(]/)[0];
  if (!["", "copy", "IA", "behaviour"].includes(d)) errors.push(`${r.id}: needs decision "${r.decision}"`);
  if (!/^(PROPOSED: (in-phase|backlog|won't-fix|closed)|fixed$)/.test(r.disp)) errors.push(`${r.id}: disposition "${r.disp}"`);
  if (!/^\[(HIGH|MEDIUM|LOW|INFO)\]/.test(r.symptom)) errors.push(`${r.id}: symptom has no severity prefix`);
  for (const m of (r.shot + " " + r.symptom).matchAll(/\]\(([^)\s]+)\)/g)) {
    const target = path.join(EVROOT, m[1]);
    if (!fs.existsSync(target)) errors.push(`${r.id}: missing link target ${m[1]}`);
  }
});

const count = (keyFn) => {
  const m = new Map();
  for (const r of rows) for (const k of [].concat(keyFn(r))) m.set(k, (m.get(k) || 0) + 1);
  return m;
};
const sev = count((r) => r.symptom.match(/^\[(\w+)\]/)[1]);
const cat = count((r) => r.cat.replace(/ \(contrast\)$/, ""));
const contrast = rows.filter((r) => r.cat.endsWith("(contrast)")).length;
const slicesOf = (s) => [...new Set(s.match(/\b(66[0-9]|670)[A-F]\b/g) || [])];
const ownerKeys = (r) => {
  const s = slicesOf(r.owner);
  if (s.length) return s;
  return [r.owner.split(/[\s(]/)[0]]; // backlog / none / fixed
};
const owner = count(ownerKeys);
const inPhase = count((r) => {
  if (!r.disp.startsWith("PROPOSED: in-phase")) return [];
  const named = slicesOf(r.disp);
  return named.length ? named.filter((s) => slicesOf(r.owner).includes(s)) : slicesOf(r.owner);
});
const decision = count((r) => r.decision.split(/[\s(]/)[0] || "(blank)");
const disp = count((r) => (r.disp === "fixed" ? "fixed" : r.disp.match(/^PROPOSED: (in-phase|backlog|won't-fix|closed)/)[1]));
const by661B = rows.filter((r) => /(caused|worsened|made stale) by 661B/.test(r.symptom)).map((r) => r.id);
const seed = rows.filter((r) => r.n <= SEED_MAX).length;
const intake = rows.filter((r) => r.n > SEED_MAX && r.n <= INTAKE_MAX).length;
const walk = rows.filter((r) => r.n > INTAKE_MAX).length;
const g = (m, k) => m.get(k) || 0;

const ownerKeysAll = [...SLICE_ORDER, "backlog", "none", "fixed"].filter((k) => owner.has(k));
for (const k of owner.keys()) if (![...SLICE_ORDER, "backlog", "none", "fixed"].includes(k)) errors.push(`unknown owner key "${k}"`);
const hrow = (cells) => `| ${cells.join(" | ")} |`;

const block = [
  "<!-- counts:start — generated by kinks/scripts/08-register-counts.cjs from the table below; do not edit by hand -->",
  `**Totals:** ${rows.length} rows = seed ${seed} (K-16 fixed; K-04 closed for label text) · intake ${intake} · walk ${walk}. Severity: HIGH ${g(sev, "HIGH")} · MEDIUM ${g(sev, "MEDIUM")} · LOW ${g(sev, "LOW")} · INFO ${g(sev, "INFO")}. Proposed: in-phase ${g(disp, "in-phase")} · backlog ${g(disp, "backlog")} · won't-fix ${g(disp, "won't-fix")} · closed ${g(disp, "closed")} · fixed ${g(disp, "fixed")}. Caused / worsened / made stale by 661B: ${by661B.join(", ")}.`,
  "",
  hrow(["**By category**", ...CATS.map((c) => (c === "other" ? `other (contrast ${contrast})` : c))]),
  hrow(["---", ...CATS.map(() => "---")]),
  hrow(["rows", ...CATS.map((c) => String(g(cat, c)))]),
  "",
  hrow(["**By owner** (a multi-slice row counts once per slice)", ...ownerKeysAll]),
  hrow(["---", ...ownerKeysAll.map(() => "---")]),
  hrow(["rows", ...ownerKeysAll.map((k) => String(g(owner, k)))]),
  hrow(["proposed in-phase", ...ownerKeysAll.map((k) => (SLICE_ORDER.includes(k) ? String(g(inPhase, k)) : "—"))]),
  "",
  hrow(["**By needs decision**", "copy", "IA", "behaviour", "blank"]),
  hrow(["---", "---", "---", "---", "---"]),
  hrow(["rows", ...["copy", "IA", "behaviour", "(blank)"].map((k) => String(g(decision, k)))]),
  "<!-- counts:end -->",
].join("\n");

console.log(block);
if (errors.length) {
  console.error(`\n${errors.length} VALIDATION ERROR(S):\n` + errors.join("\n"));
  process.exit(1);
}
if (!CHECK) {
  const re = /<!-- counts:start[\s\S]*?<!-- counts:end -->/;
  if (!re.test(text)) throw new Error("counts markers not found in kinks-register.md");
  fs.writeFileSync(REG, text.replace(re, block));
  console.log(`\nwrote counts into ${path.relative(process.cwd(), REG)} (${rows.length} rows validated)`);
}
