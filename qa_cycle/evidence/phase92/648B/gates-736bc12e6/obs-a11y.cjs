// 648B @736bc12e6 — read-only OBS of the pass-4 dialog changes (no submit; no writes).
const { chromium } = require("/Users/rakheendama/Projects/2026/worktree-epic-648B/frontend/node_modules/@playwright/test");
const fs = require("fs");
const OUT = __dirname + "/obs";
const BASE = "http://localhost:3001", ORG = `${BASE}/org/e2e-test-org`;
const r = { consoleErrors: [], pageErrors: [], checks: {} };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 1100 }, timezoneId: "Africa/Johannesburg" });
  const p = await ctx.newPage();
  p.on("console", (m) => { if (m.type() === "error") r.consoleErrors.push(m.text()); });
  p.on("pageerror", (e) => r.pageErrors.push(String(e)));
  await p.goto(`${BASE}/mock-login`, { waitUntil: "load" });
  await p.getByRole("button", { name: "Sign In", exact: true }).click();
  await p.waitForURL(/\/org\//, { timeout: 60000 });
  await p.waitForLoadState("networkidle").catch(() => {});
  await p.goto(`${ORG}/trust-accounting/investments`, { waitUntil: "load" });
  await p.getByTestId("investments-page").waitFor({ timeout: 60000 });
  await p.waitForLoadState("networkidle").catch(() => {});
  const btn = p.getByRole("button", { name: "Record interest", exact: true }).first();
  await btn.click();
  const dlg = p.getByRole("dialog");
  await dlg.waitFor();
  await p.waitForTimeout(800);
  const group = dlg.getByRole("radiogroup");
  r.checks.radiogroupName = await group.evaluate((el) => {
    const id = el.getAttribute("aria-labelledby"); return id ? (document.getElementById(id)?.textContent || "").trim() : el.getAttribute("aria-label");
  });
  const date = dlg.locator('input[type="date"], input[name="entryDate"]').first();
  const gross = dlg.locator('input[name="grossAmount"]').first();
  const fund = dlg.locator('input[name="fundShareAmount"]').first();
  r.checks.dateAriaRequired = await date.getAttribute("aria-required");
  r.checks.grossAriaRequired = await gross.getAttribute("aria-required");
  r.checks.fundAriaRequired = await fund.getAttribute("aria-required").catch(() => "n/a");
  r.checks.dateDefault = await date.inputValue();
  const today = new Intl.DateTimeFormat("en-CA", { timeZone: "Africa/Johannesburg" }).format(new Date());
  r.checks.todaySAST = today;
  await gross.fill("100");
  await p.screenshot({ path: `${OUT}/01-dialog-open-advice.png` });
  r.checks.dialogText = (await dlg.innerText()).replace(/\s+/g, " ").slice(0, 600);
  await dlg.getByRole("button", { name: "Cancel" }).click();
  await dlg.waitFor({ state: "hidden" });
  await btn.click(); await p.getByRole("dialog").waitFor(); await p.waitForTimeout(500);
  r.checks.grossAfterReopen = await p.getByRole("dialog").locator('input[name="grossAmount"]').first().inputValue();
  r.checks.dateAfterReopen = await p.getByRole("dialog").locator('input[type="date"], input[name="entryDate"]').first().inputValue();
  await p.screenshot({ path: `${OUT}/02-dialog-reopened.png` });
  fs.writeFileSync(`${OUT}/obs-a11y-result.json`, JSON.stringify(r, null, 2));
  console.log(JSON.stringify(r.checks, null, 1), "console", r.consoleErrors.length, "page", r.pageErrors.length);
  await browser.close();
})().catch((e) => { console.error("OBS FAILED", e); process.exit(1); });
